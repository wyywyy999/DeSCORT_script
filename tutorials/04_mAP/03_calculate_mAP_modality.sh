#!/bin/bash
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd -- "$SCRIPT_DIR/../.." && pwd)"
RESOURCE_ROOT="${DESCORT_RESOURCE_ROOT:-$PROJECT_ROOT/../../common_files}"
cd "$SCRIPT_DIR"

# ============================================================================
# 03_calculate_mAP_modality.sh
#
# Launch 02_calculate_mAP.py for each cross-modality combination defined in
# cross_modality_palte_dict.pkl.
#
# The dict structure: {cell_line: {modality: [plate_list]}}
# Each (cell_line, modality) pair runs as a separate mAP job with its own
# plate list and save path.
# ============================================================================

# -------------------------------
# Cross-modality plate dict
# -------------------------------
PLATE_DICT="/fse/home/wangyongyan/Project/CellPainting/DeSCORT/src/tutorials/04_mAP/cross_modality_palte_dict.pkl"

# -------------------------------
# mAP type
# -------------------------------
# replicates_activity | sister_activity | sister_consistency
mAP_type="replicates_activity"
# mAP_type="sister_activity"
# mAP_type="sister_consistency"

# -------------------------------
# Source data paths
# -------------------------------
# Embedding parquet files generated by 01_calculate_emb.py
source_data_paths="/fse/home/wangyongyan/Project/CellPainting/Paper_LLm/tutorials/01_mAP/well_level_new_site_pretrain_emb_attention_mask/cpg0000_JUMP"
# source_data_paths="/fse/DC/CP_data/feature_data/cpg000_jump_pilot/raw_data_bulk_download/A549/Compound/raw_data/normalization_clip_data_select_feature"
# source_data_paths="/fse/DC/CP_data/feature_data/cpg000_jump_pilot/raw_data_bulk_download/A549/Crispr/raw_data/normalization_clip_data_select_feature"
# source_data_paths="/fse/DC/CP_data/feature_data/cpg000_jump_pilot/raw_data_bulk_download/A549/Orf/raw_data/normalization_clip_data_select_feature"
# source_data_paths="/fse/DC/CP_data/feature_data/cpg000_jump_pilot/raw_data_bulk_download/U2OS/Crispr/raw_data/normalization_clip_data_select_feature/2020_11_04_CPJUMP1"

# -------------------------------
# Pickle / vocabulary files
# -------------------------------
# Per cell line: A549 uses cpg0000_A549, U2OS uses cpg0000_U2OS
FEATURE_LIST_A549="/fse/home/wangyongyan/Project/CellPainting/Final_well_level_new_LLM/common_files/00_pretrain/cpg0000_A549/cpg0000_A549_all_union_feature_2967.pkl"
FEATURE_LIST_U2OS="/fse/home/wangyongyan/Project/CellPainting/Final_well_level_new_LLM/common_files/00_pretrain/cpg0000_U2OS/cpg0000_U2OS_all_union_feature_2705.pkl"

feature2index_pkl="/fse/home/wangyongyan/Project/CellPainting/Final_well_level_new_LLM/common_files/00_pretrain/feature2index_vocabulary_7366.pkl"

# -------------------------------
# Output base path
# -------------------------------
# Results saved to: ${save_base_path}/${cell_line}/${modality}/
save_base_path="/fse/home/wangyongyan/Project/CellPainting/Paper_LLm/tutorials/01_mAP/well_level_attention_mask_result/replicates_level/perturbation_activity/well-level/cross_modality"

# -------------------------------
# Column / gene settings
# -------------------------------
# For cpg0000 JUMP Compound data, use:
#   perturbation_gene_key="Metadata_Broad_Sample"
#   sgRNA_barcode_key="Metadata_Broad_Sample"
#   need_columns="Metadata_Broad_Sample Metadata_Treatment Metadata_Well"
#   group_by_columns="Metadata_Broad_Sample Metadata_Treatment Metadata_Well"
#   negative_control_list="DMSO"
#
# For cpg0000 JUMP CRISPR data, use:
#   perturbation_gene_key="Metadata_Treatment"
#   sgRNA_barcode_key="Metadata_Target_Sequence"
#   need_columns="Metadata_Treatment Metadata_Target_Sequence Metadata_Well"
#   group_by_columns="Metadata_Treatment Metadata_Target_Sequence Metadata_Well"
#   negative_control_list="nontargeting"

perturbation_gene_key="Metadata_Broad_Sample"
# perturbation_gene_key="Metadata_Treatment"

sgRNA_barcode_key="Metadata_Broad_Sample"
# sgRNA_barcode_key="Metadata_Target_Sequence"

negative_control_list="DMSO"
# negative_control_list="nontargeting"

# -------------------------------
# Aggregation / processing
# -------------------------------
choose_type="well-level"

do_intersect_features=false
do_groupby_mean=true

need_columns="Metadata_Broad_Sample Metadata_Treatment Metadata_Well"
# need_columns="Metadata_Treatment Metadata_Target_Sequence Metadata_Well"

group_by_columns="Metadata_Broad_Sample Metadata_Treatment Metadata_Well"
# group_by_columns="Metadata_Treatment Metadata_Target_Sequence Metadata_Well"

# -------------------------------
# mAP calculation settings
# -------------------------------
random_seeds="42 2026 2025 2024 2023"
# random_seeds="42"
n_jobs=20
sample_method="random"
# sample_method="all"
n_number=2

# -------------------------------
# Logging
# -------------------------------
log_base="/fse/home/wangyongyan/Project/CellPainting/DeSCORT/src/tutorials/04_mAP"
log_level="INFO"

# ============================================================================
# Iterate over cell lines and modalities from the plate dict
# ============================================================================

# Get all cell_line:modality combinations
combos=$(python3 -c "
import pickle
with open('${PLATE_DICT}', 'rb') as f:
    d = pickle.load(f)
for cell_line in sorted(d):
    for modality in sorted(d[cell_line]):
        print(f'{cell_line}:{modality}')
")

total=$(echo "$combos" | wc -l)
current=0

for combo in $combos; do
    current=$((current + 1))
    cell_line=$(echo "$combo" | cut -d: -f1)
    modality=$(echo "$combo" | cut -d: -f2)

    echo ""
    echo "============================================================"
    echo "[${current}/${total}] cell_line=${cell_line}  modality=${modality}"
    echo "============================================================"

    # ---- Select feature list per cell line ----
    if [ "$cell_line" = "A549" ]; then
        need_feature_list_pkl="$FEATURE_LIST_A549"
    elif [ "$cell_line" = "U2OS" ]; then
        need_feature_list_pkl="$FEATURE_LIST_U2OS"
    else
        echo "ERROR: Unknown cell line: $cell_line"
        continue
    fi

    # ---- Get plate list from dict ----
    plates=$(python3 -c "
import pickle
with open('${PLATE_DICT}', 'rb') as f:
    d = pickle.load(f)
print(' '.join(d['${cell_line}']['${modality}']))
")

    if [ -z "$plates" ]; then
        echo "WARNING: No plates found for ${cell_line}/${modality}, skipping"
        continue
    fi

    echo "Plates: $plates"

    # ---- Build save path ----
    save_path="${save_base_path}/${cell_line}/${modality}"

    # ---- Build log file ----
    log_file="${log_base}/calculate_mAP_modality_${cell_line}_${modality}.log"

    # ---- Build args ----
    args=(
        --mAP_type "$mAP_type"
        --source_data_paths "$source_data_paths"
        --need_feature_list_pkl "$need_feature_list_pkl"
        --feature2index_pkl "$feature2index_pkl"
        --save_path "$save_path"
        --perturbation_gene_key "$perturbation_gene_key"
        --sgRNA_barcode_key "$sgRNA_barcode_key"
        --choose_type "$choose_type"
        --need_columns $need_columns
        --group_by_columns $group_by_columns
        --need_plate_list $plates
        --random_seeds $random_seeds
        --n_jobs "$n_jobs"
        --sample_method "$sample_method"
        --n_number "$n_number"
        --log_file "$log_file"
        --log_level "$log_level"
    )

    if [ -n "$negative_control_list" ]; then
        args+=(--negative_control_list $negative_control_list)
    fi

    if [ "$do_intersect_features" = true ]; then
        args+=(--do_intersect_features)
    fi

    if [ "$do_groupby_mean" = true ]; then
        args+=(--do_groupby_mean)
    fi

    echo "Save path: $save_path"
    echo "Log file:  $log_file"
    echo "Running 02_calculate_mAP.py ..."

    python 02_calculate_mAP.py "${args[@]}" "$@"

    echo "Done: ${cell_line}/${modality}"
done

echo ""
echo "All ${total} modality combinations processed!"